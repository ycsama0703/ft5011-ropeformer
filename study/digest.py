"""Write results/digest.md: every number the report uses, from the run directories, in one place.

    python study/digest.py --runs runs --probe results/probe_slow_group.csv --out results/digest.md
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "study"))
from aggregate import ORDER, collect, select_bases  # noqa: E402

pd.set_option("display.width", 250)


def md(frame: pd.DataFrame, digits=4) -> str:
    return frame.round(digits).to_markdown()


def paired_diffs(frame, ref, new, base):
    """Relative test-MSE reduction of `new` vs `ref` per (dataset, seed); base None = validation-selected bases."""
    source = select_bases(frame) if base is None else frame[(frame.base == base) | frame.base.isna()]
    diffs = []
    for d in sorted(set(source.dataset)):
        f = source[source.dataset == d]
        r = f[f.name == ref].set_index("seed").test_mse
        n = f[f.name == new].set_index("seed").test_mse
        for s in r.index.intersection(n.index):
            diffs.append(100 * (r[s] - n[s]) / r[s])
    return np.array(diffs)


def wilcoxon_rows(frame, pairs, bases, label):
    rows = []
    for base in bases:
        for ref, new in pairs:
            diffs = list(paired_diffs(frame, ref, new, base))
            if len(diffs) < 5:
                continue
            diffs = np.array(diffs)
            rows.append(dict(setting=label, base="selected" if base is None else f"{base:g}", comparison=f"{new} vs {ref}",
                             pairs=len(diffs), mean_pct=diffs.mean(), median_pct=np.median(diffs),
                             wins=f"{int((diffs > 0).sum())}/{len(diffs)}", p=stats.wilcoxon(diffs).pvalue))
    return rows


def selected(frame):
    """Validation-selected base per (dataset, variant), like aggregate.select_bases."""
    return select_bases(frame)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--runs", type=Path, default=ROOT / "runs")
    p.add_argument("--probe", type=Path, default=ROOT / "results" / "probe_slow_group.csv")
    p.add_argument("--out", type=Path, default=ROOT / "results" / "digest.md")
    args = p.parse_args()
    full = collect(args.runs)
    main_lr = full.scale_lr.isna() | np.isclose(full.scale_lr, 1e-2)
    std = full[main_lr & (full.steps == 3000)]
    s012 = std[std.seed.isin([0, 1, 2])]
    point = s012[~s012.name.str.startswith("P")]
    patch = s012[s012.name.str.startswith("P") | s012.name.isin(["RLinear", "Naive", "SNaive", "LSTM"])]
    out = ["# Results digest (deterministic runs; auto-generated by study/digest.py)", ""]

    # 1. main table, point tokens, seeds 0-2
    sel = selected(point)
    cols = ["Naive", "SNaive", "RLinear", "LSTM", "A", "B", "C", "D"]
    ds = [d for d in ORDER if d in set(point.dataset)]
    for metric in ("test_mse", "train_mse"):
        t = sel.groupby(["dataset", "name"])[metric].agg(["mean", "std"]).unstack("name")
        tm = t["mean"].reindex(index=ds, columns=[c for c in cols if c in t["mean"].columns])
        out += [f"## 1. Point-token backbone, seeds 0-2, validation-selected base: {metric} (mean)", md(tm), ""]
        ts = t["std"].reindex(index=ds, columns=[c for c in cols if c in t["std"].columns])
        out += [f"sd over seeds ({metric})", md(ts), ""]
    bases = sel[sel.name.isin(list("ABCD"))].groupby(["dataset", "name"]).base.first().unstack().reindex(ds)
    out += ["## 2. Selected RoPE base per variant (validation MSE)", md(bases, 0), ""]

    # 3. seed-level tests, point tokens
    rows = wilcoxon_rows(point, [("A", "B"), ("A", "D"), ("B", "D"), ("D", "C"), ("A", "C")], [None, 100.0, 10000.0], "point 3k")
    rows += wilcoxon_rows(point, [("D", "E"), ("B", "E")], [None, 100.0, 10000.0], "point 3k (G=4, 4 datasets)")
    rows += wilcoxon_rows(point, [("D", "F"), ("A", "F"), ("B", "F")], [None, 100.0, 10000.0], "point 3k (G=8, 9 datasets)")
    rows += wilcoxon_rows(point, [("A", "S"), ("S", "D")], [100.0, 10000.0], "point 3k (p-RoPE, 9 datasets)")
    # 4. patch backbone 3k
    rows += wilcoxon_rows(patch, [("PA", "PB"), ("PA", "PD"), ("PB", "PD"), ("PD", "PF"), ("PA", "PS"), ("PS", "PD")],
                          [None, 10.0, 10000.0], "patch 3k")
    # 5. patch 12k
    long = full[main_lr & (full.steps == 12000)]
    rows += wilcoxon_rows(long, [("PA", "PB"), ("PA", "PD"), ("PB", "PD")], [None, 10.0, 10000.0], "patch 12k")
    out += ["## 3. Seed-level Wilcoxon signed-rank tests over (dataset, seed) pairs",
            "mean_pct = mean relative test-MSE reduction of the first model vs the second (positive = first better)",
            md(pd.DataFrame(rows), 4), ""]

    # per-dataset patch tables
    for steps, frame in (("3000", s012), ("12000", long)):
        f = frame[frame.name.str.startswith("P") | (frame.name == "RLinear")]
        if f.empty:
            continue
        sp = selected(f)
        t = sp.groupby(["dataset", "name"]).test_mse.mean().unstack().reindex([d for d in ORDER if d in set(sp.dataset)])
        out += [f"## 4. Patch backbone ({steps} steps), validation-selected base: test MSE (mean over seeds 0-2)", md(t), ""]
        if "RLinear" in t and "PD" in t:
            gap = (100 * (t["RLinear"] - t["PD"]) / t["RLinear"]).rename("PD better than RLinear (%)")
            out += [md(gap.to_frame(), 2), ""]

    # point-token per-base means
    pb = point[point.name.isin(list("ABCDS"))].groupby(["dataset", "base", "name"]).test_mse.mean().unstack("name")
    out += ["## 5. Point-token backbone: test MSE by base (mean over seeds 0-2)", md(pb), ""]

    # 6. learned scales of D at base 1e4 and 100 (final, best checkpoint)
    try:
        sc = pd.read_csv(ROOT / "results" / "scale_summary.csv")
        out += ["## 6. Learned scales (D and B, base 1e4, best checkpoint, mean over layers/heads/seeds)", md(sc, 3), ""]
    except FileNotFoundError:
        pass

    # 7. probe
    if args.probe.exists():
        pr = pd.read_csv(args.probe)
        pr = pr[pr.seed.isin([0, 1, 2])]
        sm = pr.groupby(["name", "base"])[["change_pct", "change_quarter_pct"]].median()
        sm["n"] = pr.groupby(["name", "base"]).size()
        out += ["## 7. Inference probe: median % change in test MSE when slow pairs stop rotating",
                "change_pct = pairs 4-7 frozen; change_quarter_pct = pairs 6-7 frozen", md(sm, 1), ""]
        per = pr[pr.name.isin(["A", "D"])].groupby(["dataset", "name", "base"]).change_pct.median().unstack(["name", "base"])
        out += ["per dataset (pairs 4-7 frozen, median over seeds)", md(per, 1), ""]

    # 8. robustness: seeds 3-4 (5 seeds on the 9 phase-1 datasets) and scale lr 5e-2
    five = std[~std.name.str.startswith("P")]
    nine = sorted(set(five[five.seed == 3].dataset))
    if nine:
        f5 = five[five.dataset.isin(nine)]
        rows = wilcoxon_rows(f5, [("A", "B"), ("A", "D"), ("B", "D")], [100.0, 10000.0], f"point 3k, seeds 0-4, {len(nine)} datasets")
        out += ["## 8. Robustness: 5 seeds", md(pd.DataFrame(rows), 4), ""]
    hi = full[np.isclose(full.scale_lr.fillna(0), 5e-2) & (full.steps == 3000)]
    if not hi.empty:
        rows = []
        for base in (100.0, 10000.0):
            for ref, new in (("B", "D"),):
                rows += wilcoxon_rows(hi, [(ref, new)], [base], "scale lr 5e-2")
            both = pd.concat([hi.assign(name=hi.name + "_hi"), point[point.name.isin(["A", "B", "D"])]])
            rows += wilcoxon_rows(both, [("A", "D_hi"), ("D", "D_hi"), ("B", "B_hi")], [base], "scale lr 5e-2 vs 1e-2")
        out += ["## 9. Scale learning rate 5e-2 (B and D; A unaffected)", md(pd.DataFrame(rows), 4), ""]

    # LaTeX: compact seed-level test table for the main text
    def cell(frame, ref, new, base):
        d = paired_diffs(frame, ref, new, base)
        if len(d) < 5:
            return "--"
        pv = stats.wilcoxon(d).pvalue
        star = "$^{**}$" if pv < 0.01 else ("$^{*}$" if pv < 0.05 else "")
        return f"{d.mean():+.2f}{star} ({int((d > 0).sum())}/{len(d)})"
    settings = [(point, 10000.0, ""), (point, 100.0, ""), (patch, 10000.0, "P"), (patch, 10.0, "P"), (long, None, "P")]
    lines = [r"\begin{tabular}{lccccc}", r"\toprule",
             r" & \multicolumn{2}{c}{point tokens ($L{=}336$), 3k steps} & \multicolumn{2}{c}{patch tokens (42), 3k steps} & patch, 12k \\",
             r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-6}",
             r"Comparison & $b=10^4$ & $b=100$ & $b=10^4$ & $b=10$ & selected $b$ \\", r"\midrule"]
    for ref, new, label in (("A", "B", "B vs A (per-head)"), ("A", "D", "D vs A (grouped)"), ("B", "D", "D vs B"),
                            ("D", "C", "C vs D (shared)"), ("A", "S", "S vs A (p-RoPE)"),
                            ("B", "F", "F vs B ($G{=}8$)"), ("D", "F", "F vs D")):
        row = [cell(frame, pre + ref, pre + new, base) for frame, base, pre in settings]
        lines.append(label + " & " + " & ".join(row) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (ROOT / "results" / "tables").mkdir(parents=True, exist_ok=True)
    (ROOT / "results" / "tables" / "tests.tex").write_text("\n".join(lines) + "\n")

    # LaTeX: patch backbone vs RLinear (test and train MSE), selected bases
    def means(frame, metric):
        sp = select_bases(frame[frame.name.isin(["PA", "PB", "PD", "RLinear"])])
        return sp.groupby(["dataset", "name"])[metric].mean().unstack()
    t3, t12 = means(s012, "test_mse"), means(long, "test_mse")
    r3, r12 = means(s012, "train_mse"), means(long, "train_mse")
    order = [d for d in ORDER if d in set(t3.index)]
    from aggregate import label as dlabel
    lines = [r"\begin{tabular}{lcccc|cccc|cc}", r"\toprule",
             r" & \multicolumn{4}{c|}{test MSE, 3k steps} & \multicolumn{4}{c|}{test MSE, 12k steps} & \multicolumn{2}{c}{train MSE, 12k} \\",
             r"Dataset & RLinear & A & B & D & RLinear & A & B & D & RLinear & D \\", r"\midrule"]
    for d in order:
        v3 = [t3.loc[d].get(c, np.nan) for c in ("RLinear", "PA", "PB", "PD")]
        v12 = [t12.loc[d].get(c, np.nan) if d in t12.index else np.nan for c in ("RLinear", "PA", "PB", "PD")]
        best3, best12 = np.nanmin(v3), np.nanmin(v12)
        f = lambda v, b: ("--" if np.isnan(v) else (f"$\\mathbf{{{v:.3f}}}$" if np.isclose(v, b) else f"{v:.3f}"))
        tr = [r12.loc[d].get(c, np.nan) if d in r12.index else np.nan for c in ("RLinear", "PD")]
        lines.append(dlabel(d) + " & " + " & ".join(f(v, best3) for v in v3) + " & " + " & ".join(f(v, best12) for v in v12)
                     + " & " + " & ".join("--" if np.isnan(v) else f"{v:.3f}" for v in tr) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (ROOT / "results" / "tables" / "patch.tex").write_text("\n".join(lines) + "\n")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out) + "\n")
    print(f"wrote {args.out} ({len(out)} blocks)")


if __name__ == "__main__":
    main()
